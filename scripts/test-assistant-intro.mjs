import assert from 'assert'; import { readFileSync } from 'fs';
import { createIntro, INTRO_FULL, INTRO_SHORT } from '../src/utils/assistantIntro.js';
const mem = () => { const m = {}; return { getItem: (k) => m[k] ?? null, setItem: (k, v) => { m[k] = v; } }; };
let t = new Date(2026, 9, 29, 9, 0); const said = []; let stops = 0; let muted = false; let on = true;
const storage = mem();
const mk = () => createIntro({ speak: (x) => { if (muted) return false; said.push(x); return true; }, stop: () => { stops++; }, enabled: () => on, storage, now: () => t });
let i = mk(); assert.equal(i.start(), 'full'); assert.equal(said[0], INTRO_FULL);
i.cancel(); assert.equal(stops, 1, 'user input cancels'); i.cancel(); assert.equal(stops, 1, 'cancel idempotent');
i = mk(); assert.equal(i.start(), 'short'); assert.equal(said[1], INTRO_SHORT);
i = mk(); assert.equal(i.start(), null, 'silent within 30 min');
t = new Date(2026, 9, 30, 8, 0); muted = true; i = mk(); assert.equal(i.start(), null, 'global mute suppresses');
muted = false; on = false; assert.equal(mk().start(), null, 'speaker toggle off suppresses');
on = true; assert.equal(mk().start(), 'full', 'muted opens do not burn the daily intro');
assert(!/gemini|openai|google|gpt|claude/i.test(INTRO_FULL + INTRO_SHORT), 'no provider names');
const s = readFileSync('src/components/home/AssistantSheet.vue', 'utf8');
assert(/onMounted\([^\n]*intro\.start\(\)/.test(s), 'opens trigger intro');
assert(/toggleMic = async \(\) => \{\n  intro\.cancel\(\)/.test(s) && /@input="intro\.cancel\(\)"/.test(s) && /onBeforeUnmount\(\(\) => \{ intro\.cancel\(\)/.test(s), 'mic/type/close cancel');
assert(s.includes('data-test="assistant-help"') && !/v-if[^>]*assistant-help"/.test(s), 'help ? always visible');
const tools = readFileSync('src/utils/assistantTools.js', 'utf8');
for (const n of ['auto_schedule', 'reschedule_task', 'complete_task', 'lock_apps', 'unlock_apps']) assert(tools.includes(`'${n}'`), n);
console.log('ok   assistant intro');
